// Builds dist/ from the repository: the shipped stylesheet and themes (from the docs build), the design tokens, one
// file per icon from the shipped sprite, the shipped frontend as the component runtime, the maps the entry points read
// (CSS-module classes, component modules, icon names) and the hand-written entry points in src/.
// The runtime carries the images the components load: 484 of the 490 shipped images are named in the shipped JS or
// CSS, so a component that draws one would otherwise render a broken image. Only video is left out (NOT_PUBLISHED),
// and the CSS rules that pointed at a left-out file are dropped so nothing 404s.
// Run `npm run content` in design-system/docs first, so its public/ds/ is current.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(pkg, '../..');
const dist = path.join(pkg, 'dist');
const from = (...p) => path.join(repo, ...p);
const read = (...p) => fs.readFileSync(from(...p), 'utf8');
const write = (p, s) => {
  fs.mkdirSync(path.dirname(path.join(dist, p)), { recursive: true });
  fs.writeFileSync(path.join(dist, p), s);
};
const asModule = (name, value) => `// Generated by scripts/build.mjs.\nexport const ${name} = ${JSON.stringify(value, null, 1)};\n`;

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });

// ---- not published: video only. The images stay, because the components load them at runtime.
const NOT_PUBLISHED = /\.(mp4|webm|mov|m4v)$/i;

// ---- CSS: the shipped component styles, the theme base colours and the glass fallback
const ds = from('design-system/docs/public/ds');
// its fonts and SVGs are files of the shipped frontend, which the package carries as runtime/
let dropped = 0;
const bundle = fs
  .readFileSync(path.join(ds, 'bundle.css'), 'utf8')
  .replace(/url\(assets\/%23/g, 'url(#')
  // a declaration pointing at artwork would 404; drop the declaration and keep the rest of the rule
  .replace(/[^;{}]+:[^;{}]*url\(assets\/[^)]*\)[^;{}]*/g, (decl) =>
    [...decl.matchAll(/url\(assets\/([^)"']+)\)/g)].some((m) => NOT_PUBLISHED.test(m[1])) ? (dropped++, '') : decl,
  )
  .replace(/url\(assets\//g, 'url(../runtime/');
write('css/components.css', bundle);
write('css/theme.css', fs.readFileSync(path.join(ds, 'theme.css'), 'utf8'));
write('css/bayrust.css', '/* Bayrust 2.8.2: the shipped component styles, then the theme base colours and the glass fallback. */\n@import "./components.css";\n@import "./theme.css";\n');

// ---- tokens: W3C-style JSON, CSS, and a typed module keyed by CSS variable
const tokens = JSON.parse(read('design-system/tokens/bayrust.tokens.json'));
write('tokens/tokens.json', JSON.stringify(tokens, null, 1));
write('tokens/tokens.css', read('design-system/tokens/tokens.css'));
const flat = {};
for (const [group, entries] of Object.entries(tokens)) {
  for (const [name, t] of Object.entries(entries)) {
    const x = t.$extensions?.bayrust ?? {};
    flat[x.cssVar ?? `--${name}`] = { group, value: t.$value, dark: x.dark ?? t.$value, light: x.light ?? t.$value };
  }
}
write('data/tokens.js', asModule('tokens', flat));

// ---- icons: one file per symbol of the shipped sprite. Each shows as an image and also holds the symbol as id "s",
// which is how the shipped Icon references it (<use href="…#s">).
const spriteFile = fs.readdirSync(from('reference/frontend')).find((f) => /^icons-.*\.svg$/.test(f));
const sprite = read('reference/frontend', spriteFile);
const icons = [];
for (const m of sprite.matchAll(/<symbol id="([^"]+)"([^>]*)>([\s\S]*?)<\/symbol>/g)) {
  const [, name, attrs, body] = m;
  const viewBox = /viewBox="([^"]+)"/.exec(attrs)?.[1] ?? '0 0 16 16';
  const [, , w, h] = viewBox.split(/\s+/);
  icons.push(name);
  write(`icons/${name}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${viewBox}"><symbol id="s"${attrs}>${body}</symbol><use href="#s"/></svg>\n`);
}
write('data/icons.js', asModule('iconNames', icons.sort()));

// ---- CSS-module classes: { module: { part: 'module__part_hash' } }, so the shipped styles work with any markup
const classes = {};
for (const [, mod, part, hash] of bundle.matchAll(/\.([a-z][a-z0-9-]*)__([A-Za-z][A-Za-z0-9]*)_([0-9a-f]{5})\b/g)) {
  (classes[mod] ??= {})[part] = `${mod}__${part}_${hash}`;
}
const sorted = Object.fromEntries(Object.keys(classes).sort().map((m) => [m, Object.fromEntries(Object.entries(classes[m]).sort())]));
write('data/classes.js', asModule('classes', sorted));

// ---- the shipped frontend, as the component runtime (its modules import each other relatively), without video
fs.cpSync(from('reference/frontend'), path.join(dist, 'runtime'), { recursive: true, filter: (f) => !f.endsWith('.html') && !NOT_PUBLISHED.test(f) });

// ---- components: name → [module, export]. Named exports from the inventory, plus the parts the docs bind by
// displayName (namespace members such as BaseButton.Root), which the loader finds by displayName.
const components = {};
for (const [name, defs] of Object.entries(JSON.parse(read('research/component-inventory.json')))) {
  const d = defs.find((x) => x.export);
  if (d) components[name] = [d.module, d.export];
}
for (const f of ['design-system/site/components.js', 'design-system/site/composed.js']) {
  for (const [, , file, name] of read(f).matchAll(/(\w+): await C\('([^']+)', '([^']+)'\)/g)) components[name] ??= [file, null];
}
write('data/components.js', asModule('components', Object.fromEntries(Object.entries(components).sort())));

// ---- entry points
fs.cpSync(path.join(pkg, 'src'), dist, { recursive: true });

const count = (d) => fs.readdirSync(path.join(dist, d), { recursive: true }).length;
const left = fs.readdirSync(from('reference/frontend')).filter((f) => NOT_PUBLISHED.test(f)).length;
console.log(`dist: ${icons.length} icons, ${Object.keys(sorted).length} CSS modules, ${Object.keys(components).length} components, ${Object.keys(flat).length} tokens, ${count('runtime')} runtime files`);
console.log(`video left out: ${left} files, ${dropped} CSS declarations that pointed at them`);
